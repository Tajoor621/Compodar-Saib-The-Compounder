export type CopyKey = keyof (typeof UI)["en"];

export function t(lang: Lang, key: CopyKey): string {
  return UI[lang][key];
}

export function patientFacingCorpus(): string {
  const chunks: string[] = [];
  for (const lang of ["en", "ur"] as const) {
    for (const value of Object.values(UI[lang])) chunks.push(value);
    for (const value of Object.values(REVIEW_LINE[lang])) chunks.push(value);
    for (const value of Object.values(DOMAIN_PLAIN[lang])) chunks.push(value);
    for (const row of Object.values(DANGER_TEXT)) {
      chunks.push(row.en, row.ur, row.roman);
    }
  }
  return chunks.join("\n");
}

export function urgencyPlain(lang: Lang, urgency: Urgency): string | null {
  if (urgency === "RED") return t(lang, "urgentNow");
  if (urgency === "AMBER") return t(lang, "within");
  if (urgency === "YELLOW") return t(lang, "routine");
  return null;
}

