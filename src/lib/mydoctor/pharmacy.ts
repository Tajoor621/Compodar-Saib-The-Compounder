export const LIBRARY: Monograph[] = [...CORE, ...MORE];

function norm(value: string): string {
  return value
    .toLowerCase()
    .normalize("NFKC")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

function namesOf(row: Monograph): string[] {
  return [row.inn, row.id, ...row.aliases, ...row.brands.map((brand) => brand.brand)];
}

function editDistance(a: string, b: string): number {
  if (Math.abs(a.length - b.length) > 1) return 2;
  const row = Array.from({ length: b.length + 1 }, (_, index) => index);
  for (let i = 1; i <= a.length; i += 1) {
    let previous = row[0];
    row[0] = i;
    for (let j = 1; j <= b.length; j += 1) {
      const current = row[j];
      row[j] = a[i - 1] === b[j - 1] ? previous : 1 + Math.min(previous, row[j], row[j - 1]);
      previous = current;
    }
  }
  return row[b.length];
}

function scoreName(query: string, name: string): number {
  if (!name || !query) return 0;
  if (name === query) return 100;
  if (name.startsWith(query) || query.startsWith(name)) return 80;
  if (query.length >= 5 && name.length >= 5 && editDistance(query, name) === 1) return 78;
  if (query.length >= 4 && name.includes(query)) return 55;
  return 0;
}

export function askName(query: string): string {
  const words = query
    .replace(/[()[\]{}"'«»?؟,.]/g, " ")
    .split(/\s+/)
    .filter((word) => word.length > 0)
    .filter((word) => !/^(what|whats|what's|is|are|does|do|did|using|used|use|uses|for|the|this|medicine|of|about|tell|me|please|how|why|when|a|an|kis|liye|kya|hai|hy|istamal|kaam|konsa|konsi|dawa|batao|bataen)$/i.test(word))
    .filter((word) => !/^(کیا|ہے|کے|لیے|لئے|استعمال|کام|کس|کونسی|کونسا|دوا|بتاؤ|بتائیں|میں)$/.test(word));
  const cleaned = words.join(" ").trim();
  return cleaned.length >= 2 ? cleaned : query.trim();
}

export function searchMedicines(query: string, limit = 6): Monograph[] {
  const q = norm(askName(query));
  if (q.length < 2) return [];
  const hits = LIBRARY.map((row) => {
    const score = Math.max(...namesOf(row).map((name) => scoreName(q, norm(name))));
    return { row, score };
  }).filter((hit) => hit.score > 0);
  hits.sort((a, b) => b.score - a.score || a.row.inn.localeCompare(b.row.inn));
  return hits.slice(0, limit).map((hit) => hit.row);
}

export function formulaParts(query: string): string[] {
  const parts = query
    .split(/\s*(?:\+|&|\/|,|\bplus\b|\bwith\b|\band\b| و )\s*/i)
    .map((part) => part.trim())
    .filter(Boolean);
  return parts.length > 0 ? parts : [query];
}

export function resolveMedicine(query: string): { named: Monograph[]; reading: Monograph | null } {
  const asked = askName(query);
  const named: Monograph[] = [];
  const seen = new Set<string>();
  const unknown: string[] = [];
  for (const part of formulaParts(asked)) {
    const hits = searchMedicines(part, 3).filter((row) => {
      const q = norm(part);
      return namesOf(row).some((name) => scoreName(q, norm(name)) >= 55);
    });
    if (hits.length === 0) {
      if (norm(part).replace(/[0-9]/g, "").trim().length >= 4 || familyFor(part)) unknown.push(part);
      continue;
    }
    const best = hits[0];
    if (!seen.has(best.id)) {
      seen.add(best.id);
      named.push(best);
    }
  }
  if (norm(asked).length < 2) return { named: [], reading: null };
  if (unknown.length === 0) return { named, reading: null };
  return { named, reading: buildReading(unknown.join(" + ")) };
}

export function medicineById(id: string): Monograph | undefined {
  return LIBRARY.find((row) => row.id === id);
}
